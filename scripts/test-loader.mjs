import { chromium } from 'playwright-core';
import { strict as assert } from 'node:assert';
const browser = await chromium.launch({executablePath:'C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe',headless:true,args:['--no-first-run','--disable-extensions']});
try {
  for (const [width,height] of [[1440,900],[360,740],[667,375]]) {
    const page = await browser.newPage({ viewport:{width,height}, reducedMotion:'no-preference' });
    const errors=[];page.on('pageerror',e=>errors.push(e.message));
    const r=await page.goto('http://127.0.0.1:3100/demo/logo-loader',{waitUntil:'domcontentloaded'});
    assert.equal(r.status(),200);
    await page.getByRole('img',{name:/HANDHELD, símbolo/}).waitFor({timeout:25000});
    const paths=await page.locator('svg path').count();
    assert(paths>10,'Expected contour paths, received '+paths);
    const w=await page.evaluate(()=>document.documentElement.scrollWidth);
    assert(w<=width+2, 'Horizontal overflow '+width+' => '+w);
    const get=()=>page.locator('svg path').first().evaluate(el=>({offset:parseFloat(el.style.strokeDashoffset),length:parseFloat(el.style.strokeDasharray)}));
    await page.getByRole('button',{name:'Reiniciar animación'}).click();
    const a=await get();
    await page.waitForTimeout(1200);
    const b=await get();
    assert(b.offset<a.offset,'Line should draw');
    await page.getByRole('button',{name:'Pausar animación'}).click();
    const frozen=await get();
    await page.waitForTimeout(350);
    const paused=await get();
    assert.equal(paused.offset,frozen.offset,'Pause must freeze');
    await page.getByRole('button',{name:'Reproducir animación'}).click();
    await page.waitForTimeout(200);
    const resumed=await get();
    assert(resumed.offset<paused.offset,'Play should resume');
    console.log('OK',width,'paths',paths,'offsets',a.offset,b.offset,resumed.offset,'errors',errors);
    assert.equal(errors.length,0);
    await page.close();
  }
  const phases=await browser.newPage();
  await phases.goto('http://127.0.0.1:3100/demo/logo-loader');
  await phases.getByRole('img',{name:/HANDHELD, símbolo/}).waitFor({timeout:20000});
  const alpha=()=>phases.evaluate(()=>{
    const f=document.querySelector('svg g[id$="-filled"]');
    const l=document.querySelector('svg g[id$="-lockup"]');
    return { fill:Number(f?.style.opacity), lockup:Number(l?.style.opacity) };
  });
  await phases.getByRole('button',{name:'Reiniciar animación'}).click();
  await phases.waitForTimeout(3450);
  const halfway=await alpha();
  assert(halfway.fill>0 && halfway.fill<1,'Fill phase should crossfade');
  await phases.waitForTimeout(650);
  const solid=await alpha();
  assert(solid.fill===1 && solid.lockup===1,'Hold phase should show full logo');
  await phases.waitForTimeout(1330);
  const fading=await alpha();
  assert(fading.lockup<1,'Reset phase should fade');
  await phases.waitForTimeout(420);
  const reset=await alpha();
  assert(reset.fill===0,'Next loop should reset to outline');
  console.log('OK full cycle',JSON.stringify({halfway,solid,fading,reset}));
  await phases.close();
  const reduced=await browser.newPage({reducedMotion:'reduce'});
  await reduced.goto('http://127.0.0.1:3100/demo/logo-loader');
  await reduced.getByRole('img',{name:/HANDHELD, símbolo/}).waitFor({timeout:20000});
  assert(await reduced.getByRole('button',{name:'Pausar animación'}).isDisabled());
  const fill=await reduced.locator('svg g[id$="-filled"]').evaluate(el=>getComputedStyle(el).opacity);
  assert.equal(fill,'1','Reduced motion must show full logo');
  console.log('OK reduced motion fill',fill);
  await reduced.close();
  const home=await browser.newPage();
  await home.goto('http://127.0.0.1:3100/');
  await home.locator('#inicio').waitFor({timeout:20000});
  console.log('OK home unaffected');
  await home.close();
} finally { await browser.close(); }
